#!/usr/bin/env node
/**
 * Generates docs/CARD_SUPPORT.md and checks that every entity the engine can produce has an
 * explicit visual in the web client.
 *
 *   ./gradlew :server:test --tests '*EntityInventoryTest*' && node tools/compatibility/card-support.mjs
 *
 * Inputs (all produced from the real engine, nothing hand-maintained):
 *   server/app/build/card-catalog.json     playable pool with level-11 stats (CardCatalog)
 *   server/app/build/entity-inventory.json entities each card produced in a real match
 *   server/engine/crforge-data/src/main/resources/cards/cards.json  every card record upstream ships
 *   server/engine/UPSTREAM_CARD_TRACKER.md upstream implementation status
 *   apps/web/src/rendering/visualCatalog.ts client visuals
 * Exit code 1 if an engine entity has no explicit visual (--check).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const catalog = JSON.parse(read('server/app/build/card-catalog.json'));
const inventory = JSON.parse(read('server/app/build/entity-inventory.json'));
const allCards = JSON.parse(read('server/engine/crforge-data/src/main/resources/cards/cards.json'));
const tracker = read('server/engine/UPSTREAM_CARD_TRACKER.md');
const visualSrc = read('apps/web/src/rendering/visualCatalog.ts');

// Visual keys: `Name: char(` / proc( / prop( / area( inside VISUALS.
const visuals = new Map();
for (const m of visualSrc.matchAll(/^\s{2}(\w+): (char|proc|prop|area)\(/gm)) visuals.set(m[1], { kind: m[2] });
const projectiles = new Set([...visualSrc.matchAll(/^\s{2}'?([\w ]+)'?: \{ look: '(\w+)'/gm)].map((m) => m[1]));

const status = new Map();
for (const m of tracker.matchAll(/^\|\s*\d+\s*\|\s*([^|]+?)\s*\|\s*(\S+)\s*\|\s*`(\w+)`\s*\|\s*([^|]*)\|/gm)) {
  status.set(m[2].toLowerCase(), { status: m[3], note: m[4].trim() });
}

const unitsByCard = new Map();
for (const [name, info] of Object.entries(inventory)) {
  for (const c of info.cards) {
    if (!unitsByCard.has(c)) unitsByCard.set(c, []);
    unitsByCard.get(c).push(name);
  }
}

const missing = [];
for (const name of Object.keys(inventory)) if (!visuals.has(name)) missing.push(name);

function graphicsFor(card) {
  const names = unitsByCard.get(card.id) ?? [];
  if (!names.length) return card.type === 'SPELL' ? 'spell VFX (procedural)' : '—';
  const kinds = new Set(names.map((n) => visuals.get(n)?.kind ?? 'fallback'));
  const label = { char: 'CC0 rigged model', proc: 'procedural model', prop: 'CC0 building', area: 'spell area VFX', fallback: 'generic fallback' };
  return [...kinds].map((k) => label[k]).join(' + ');
}

const fmtStats = (c) => {
  if (c.unit) {
    const u = c.unit;
    return `HP ${u.hp}, DMG ${u.damage}, hit ${u.hitSpeed}s, range ${(u.range / 1000).toFixed(1)}, ${u.target.toLowerCase()}${u.movement === 'AIR' ? ', air' : ''}${c.count > 1 ? `, ×${c.count}` : ''}`;
  }
  if (c.spell) return `radius ${(c.spell.radius / 1000).toFixed(1)}, DMG ${c.spell.damage}${c.spell.duration ? `, ${c.spell.duration}s` : ''}`;
  return '';
};

const pool = catalog.cards;
const poolIds = new Set(pool.map((c) => c.id));
const lines = [];
lines.push('# Card support');
lines.push('');
lines.push('_Generated by `tools/compatibility/card-support.mjs` from engine data and test output — do not edit by hand._');
lines.push('');
lines.push(`- Card records in crforge \`cards.json\`: **${allCards.length}** (includes sub-entities, evolution/hero variants, champions, game-mode cards).`);
lines.push(`- Playable in AnyRoyale matches: **${pool.length}** — each one deployed in a real engine match by \`CardPoolSmokeTest\` (passes) and drawn by the client.`);
lines.push(`- Distinct engine entities those cards produce: **${Object.keys(inventory).length}**; entities without an explicit client visual: **${missing.length}**${missing.length ? ` (${missing.join(', ')})` : ''}.`);
lines.push(`- All stats are at level ${catalog.level} (every card and tower in every match uses this level).`);
lines.push('- Audio: every card uses synthesised effects by category (deploy, melee type, ranged type, spell type, death); there are no per-card voice lines.');
lines.push('- "Visual match" is never claimed: models are CC0 stand-ins (see docs/ASSETS.md).');
lines.push('');
lines.push('| Card ID | Name | Type | Cost | Stats (level 11) | Units produced | Engine | Web | Graphics | Audio | Tested | In matches |');
lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const c of pool) {
  const units = (unitsByCard.get(c.id) ?? []).join(', ') || '—';
  const webOk = (unitsByCard.get(c.id) ?? []).every((n) => visuals.has(n));
  lines.push(`| \`${c.id}\` | ${c.name} | ${c.type.toLowerCase()} | ${c.cost} | ${fmtStats(c)} | ${units} | ✅ | ${webOk ? '✅' : '⚠️ fallback'} | ${graphicsFor(c)} | synth | ✅ smoke + inventory | ✅ |`);
}
lines.push('');
lines.push('## Not in matches');
lines.push('');
lines.push('| Card ID | Name | Type | Reason |');
lines.push('|---|---|---|---|');
for (const c of allCards) {
  if (poolIds.has(c.id) || c.cost === 0) continue;
  let reason;
  if (c.type === 'HERO') reason = 'Champion: ability cycling not implemented upstream (PARTIAL/MISSING)';
  else if (c.id.endsWith('_ev1')) reason = 'Evolution variant: evolution cycle and abilities not implemented upstream';
  else if (c.id.endsWith('_hero')) reason = 'Hero variant: hero mechanics not implemented upstream';
  else {
    const st = status.get(c.id);
    reason = st ? `Upstream status ${st.status}${st.note ? ` (${st.note})` : ''}` : 'Not tracked as DONE upstream';
  }
  lines.push(`| \`${c.id}\` | ${c.name} | ${c.type.toLowerCase()} | ${reason} |`);
}
lines.push('');
lines.push('Sub-entities with cost 0 (bombs, bottles, containers) are not cards; they appear in matches only as death/spawn effects of playable cards.');
lines.push('');
fs.writeFileSync(path.join(root, 'docs', 'CARD_SUPPORT.md'), lines.join('\n'));
console.log(`docs/CARD_SUPPORT.md: ${pool.length} playable cards, ${Object.keys(inventory).length} entities, ${missing.length} without explicit visual`);
if (process.argv.includes('--check') && missing.length) {
  console.error('Entities without visuals:', missing);
  process.exit(1);
}
void projectiles;
